"""[v3 2026-09-02] Age composition of the projected work-from-home population,
P(age | WFH), for manuscript tables tab:wfh-age-tx / tab:wfh-age-oh (app:commute-joint).

The v2 manuscript tables were produced ad hoc (no script survived); the recipe below
reproduces the v2 numbers EXACTLY from the v2 artifacts (checked 2026-09-02: TX 2024
TTVAE 0.0/20.0/39.6/34.2/6.2, disc 0.095; SemaPop 0.127; WGAN 0.311; TVAE 0.171;
FlowSyn 0.074), and is the same arithmetic as panel (c) of make_L2_commute_figure.py:
  * ensemble = concat of every projected_weights realization file of the cell,
    weights = projected_weight (normalised over the pooled ensemble);
  * P(age|WFH) over Age_Group bins [0-17, 18-34, 35-49, 50-64, 65+] restricted to
    Commute_Mode == Worked_at_home;
  * realized = PWGTP-weighted reference_<year>_<ST>.csv, same conditioning;
  * discrepancy = 0.5 * sum_a |p_hat_a - p*_a|  (TVD, Layer-1 marginal-discrepancy form).
Cells: the manuscript criterion -- every Layer-1-passing prior at the 2024 horizon in
the states that contain BOTH Layer-2-accepted (P) and Layer-2-rejected (F) cells at
2024 -- is applied programmatically; columns are ordered by ascending chi_H (which is
the order of the v2 tables: P columns first, then F).
Outputs (this directory): wfh_age_<ST>_2024.csv, wfh_age_<ST>_2024.tex, wfh_age_all.csv
"""
import sys
from pathlib import Path
import numpy as np, pandas as pd
HERE = Path(__file__).resolve().parent; sys.path.insert(0, str(HERE))
import ablation_lib as A
V3 = HERE.parent
YEAR = 2024
WFH = "Worked_at_home"
AGES = ["0-17", "18-34", "35-49", "50-64", "65+"]
DISP = {"semapop_vae": "SemaPop-VAE+", "ttvae": "TTVAE", "tabddpm": "TabDDPM", "bn": "BN",
        "wgan_zcr": "WGAN-GP-ZCR", "ctgan": "CTGAN", "flowsyn": "FlowSyn",
        "borysov": "Borysov-VAE", "tvae": "TVAE"}
TEX_DISP = dict(DISP, wgan_zcr="WGAN")          # v2 table header abbreviated WGAN-GP-ZCR as WGAN
STATE_NAME = {"CA": "California", "TX": "Texas", "OH": "Ohio"}


def add_ag(df):
    if "Age_Group" not in df.columns:
        df["Age_Group"] = pd.cut(pd.to_numeric(df.Age, errors="coerce"), [0, 18, 35, 50, 65, 200],
                                 labels=AGES, right=False, include_lowest=True).astype(str)
    return df


def agedist(df, w, m):
    s = pd.Series(w[m]).groupby(df.Age_Group.astype(str).values[m]).sum()
    s = s.reindex(AGES).fillna(0)
    return (s / s.sum()).values


c = pd.read_csv(V3 / "xstate_certificate_all.csv"); c["year"] = c.year.astype(int)
l1 = c[(c.L1_accept == True) & (c.year == YEAR)].copy()
l1["L2pass"] = l1.L2_accept == True
states = [s for s, g in l1.groupby("state") if g.L2pass.any() and (~g.L2pass).any()]
print(f"states with both L2-pass and L2-fail L1-pass cells at {YEAR}: {states}")

long = []
for st in states:
    ref = add_ag(pd.read_csv(f"{A.ROOT}/data/pums_states/{st}/reference_{YEAR}_{st}.csv"))
    rw = pd.to_numeric(ref.PWGTP, errors="coerce").fillna(0).to_numpy(float); rw /= rw.sum()
    pr = agedist(ref, rw, (ref.Commute_Mode.astype(str) == WFH).values)
    cols = {"Realized": pr}; heads = []; discs = []
    g = l1[l1.state == st].sort_values("L2_chi_H")
    for _, r in g.iterrows():
        fs = A._pw_files(r.model, st, str(YEAR))
        ens = add_ag(pd.concat([pd.read_csv(f) for f in fs], ignore_index=True))
        q = ens.projected_weight.to_numpy(float); q /= q.sum()
        pq = agedist(ens, q, (ens.Commute_Mode.astype(str) == WFH).values)
        disc = 0.5 * np.abs(pq - pr).sum()
        tag = "P" if r.L2pass else "F"
        cols[f"{DISP[r.model]} ({tag})"] = pq; heads.append((r.model, tag)); discs.append(disc)
        for a, v, vr in zip(AGES, pq, pr):
            long.append(dict(state=st, year=YEAR, model=r.model, display=DISP[r.model], L2=tag,
                             chi_H=r.L2_chi_H, n_realizations=len(fs), age=a,
                             p_proj_pct=100 * v, p_real_pct=100 * vr, discrepancy=disc))
    tab = pd.DataFrame(cols, index=AGES) * 100
    tab.loc["discrepancy vs realized"] = [np.nan] + discs
    tab.index.name = "Age"
    tab.round(3).to_csv(HERE / f"wfh_age_{st}_{YEAR}.csv")
    print(f"\n{st} {YEAR}  P(age|WFH) (%)"); print(tab.round(3).to_string())
    # ---- LaTeX in the manuscript's layout ----
    hdr = " & ".join([f"\\texttt{{{TEX_DISP[m]}}}\\,({t})" for m, t in heads])
    lines = [f"\\begin{{tabular}}{{l{'c' * (len(heads) + 1)}}}", "\\toprule",
             f"Age & Realized & {hdr} \\\\", "\\midrule"]
    for a in AGES:
        lab = a.replace("-", "--")
        vals = " & ".join(f"{v:.1f}" for v in tab.loc[a].values)
        lines.append(f"{lab:6s} & {vals} \\\\")
    lines += ["\\midrule",
              "discrepancy vs realized & -- & " + " & ".join(f"{d:.3f}" for d in discs) + " \\\\",
              "\\bottomrule", "\\end{tabular}"]
    (HERE / f"wfh_age_{st}_{YEAR}.tex").write_text(
        f"% auto-generated by ablation_l2/make_wfh_age_tables.py (v3, {STATE_NAME[st]} {YEAR}); "
        f"columns = L1-pass priors ordered by chi_H; (P)=L2 accepted, (F)=L2 rejected\n" + "\n".join(lines) + "\n")
pd.DataFrame(long).to_csv(HERE / "wfh_age_all.csv", index=False)
print(f"\nwrote wfh_age_<ST>_{YEAR}.csv/.tex for {states} and wfh_age_all.csv ({len(long)} rows)")
