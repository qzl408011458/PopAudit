"""
Wrapper to generate persona text for the TX state dataset.

Usage:
  # full run (40K train + 10K val persona generations; ~15-20h on A100)
  python data_prep/pums_states/TX/run_persona_TX.py --device cuda:1

  # smoke test: only N rows from train + val (verify pipeline before full launch)
  python data_prep/pums_states/TX/run_persona_TX.py --device cuda:1 --smoke 10

Mode: Mode A (abstract/pers) — use_iot=True, random_per=False.

Outputs to data/pums_states/TX/:
  traindata_pers.csv      (Mode A → file name suffix '_pers')
  valdata_pers.csv
  testdata_pers.csv       (no persona, fast; columns only)
"""
from __future__ import annotations
import argparse
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

# Reuse persona script's helpers directly.
import _gen_pub_personas_traintest as gp

# Pin task to TX state paths.
DATA_NAME = "pums_states/TX"
CSV_PATH = ROOT / f"data/{DATA_NAME}/person_level_2013_TX.csv"
IDS_PKL = ROOT / f"data/{DATA_NAME}/dataset_ids.pkl"
OUT_DIR = ROOT / f"data/{DATA_NAME}"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--device", default="cuda:0",
                   help="GPU device for Qwen3-8B persona generator (e.g. cuda:0, cuda:1).")
    p.add_argument("--smoke", type=int, default=0,
                   help="If >0, run a smoke test with this many train + val rows only.")
    p.add_argument("--no_test", action="store_true",
                   help="Skip writing testdata_pers.csv.")
    p.add_argument("--shard_id", type=int, default=0,
                   help="Which shard (0-based) of train+val to process. Use with --num_shards for multi-GPU parallel runs.")
    p.add_argument("--num_shards", type=int, default=1,
                   help="Total number of shards. If >1, train/val indices are interleaved across shards; outputs are suffixed with _shard{K}.")
    args = p.parse_args()

    if args.num_shards < 1 or not (0 <= args.shard_id < args.num_shards):
        raise ValueError(f"Invalid sharding: shard_id={args.shard_id}, num_shards={args.num_shards}")

    print(f"TX state persona generation")
    print(f"  csv: {CSV_PATH}")
    print(f"  ids: {IDS_PKL}")
    print(f"  out: {OUT_DIR}")
    print(f"  device: {args.device}")
    print(f"  mode: A (use_iot=True, random_per=False)")
    print(f"  sharding: {args.shard_id}/{args.num_shards}")
    if args.smoke:
        print(f"  SMOKE TEST: only {args.smoke} train + {args.smoke} val rows")

    import pandas as pd
    df = pd.read_csv(CSV_PATH)
    df = gp._maybe_restore_index(df)
    train_idx, val_idx, test_idx = gp.load_split_indices(str(IDS_PKL))

    if args.smoke:
        train_idx = train_idx[:args.smoke]
        val_idx = val_idx[:args.smoke] if val_idx else None
        test_idx = test_idx[:args.smoke]

    # Apply sharding (interleaved so each shard sees uniform distribution).
    if args.num_shards > 1:
        train_idx = train_idx[args.shard_id::args.num_shards]
        if val_idx:
            val_idx = val_idx[args.shard_id::args.num_shards]
        # Test only generated by shard 0 (it's fast, no persona needed).
        if args.shard_id != 0:
            test_idx = []
        suffix = f"_shard{args.shard_id}"
    else:
        suffix = ""

    print(f"\n  loading Qwen3-8B generator on {args.device} ...")
    generator = gp.Persona_Generator(device=args.device)

    print(f"\n  >>> TRAIN persona generation ({len(train_idx)} rows) <<<")
    gp.generate_split_csv(
        df=df, indices=train_idx, type_name=f"train{suffix}",
        generator=generator, out_dir=str(OUT_DIR),
        use_iot=True, random_per=False, gen_persona=True,
    )

    if val_idx:
        print(f"\n  >>> VAL persona generation ({len(val_idx)} rows) <<<")
        gp.generate_split_csv(
            df=df, indices=val_idx, type_name=f"val{suffix}",
            generator=generator, out_dir=str(OUT_DIR),
            use_iot=True, random_per=False, gen_persona=True,
        )

    if not args.no_test and len(test_idx) > 0:
        print(f"\n  >>> TEST set (no persona, just attributes; {len(test_idx)} rows) <<<")
        gp.generate_split_csv(
            df=df, indices=test_idx, type_name="test",
            generator=None, out_dir=str(OUT_DIR),
            use_iot=True, random_per=False, gen_persona=False,
        )

    if args.num_shards > 1:
        print(f"\n✅ shard {args.shard_id}/{args.num_shards} complete. After ALL shards done, run merge_shards.py to assemble traindata_pers.csv + valdata_pers.csv.")
    else:
        print("\n✅ persona generation complete. Next: run run_emb_CA.py.")


if __name__ == "__main__":
    main()
